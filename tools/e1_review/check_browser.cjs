// Uses an existing Playwright installation; the review page itself has no dependencies.
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const {pathToFileURL} = require("node:url");
const {chromium} = require("playwright");

(async () => {
  const html = path.resolve(process.argv[2] || "runs/e1-manual-review/index.html");
  const browser = await chromium.launch({headless:true, executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  const context = await browser.newContext({viewport:{width:1440,height:1100},acceptDownloads:true});
  const page = await context.newPage(), errors = [], requests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), "kenggo-review-browser-"));
  try {
    await page.goto(pathToFileURL(html).href);
    assert.equal(await page.locator(".queue button").count(),2);
    assert.match(await page.locator(".result-row").innerText(), /B\+15.50/);
    await page.getByRole("combobox",{name:"Cleanup budget"}).selectOption("32");
    const source = page.getByRole("region",{name:"Source game",exact:true});
    await source.getByRole("button",{name:"Start",exact:true}).click();
    assert.match(await source.locator(".move-label").innerText(),/^0 \/ /);
    await source.getByRole("button",{name:"→",exact:true}).click();
    assert.match(await source.locator(".move-label").innerText(),/^1 \/ /);
    await page.getByRole("textbox",{name:"Review notes",exact:true}).fill("Browser test: inspect group at D4.");
    await page.getByRole("combobox",{name:"Review status"}).selectOption("followup");
    await page.reload();
    assert.equal(await page.getByRole("textbox",{name:"Review notes",exact:true}).inputValue(),"Browser test: inspect group at D4.");
    assert.equal(await page.getByRole("combobox",{name:"Review status"}).inputValue(),"followup");
    const otherTab = await context.newPage();
    await otherTab.goto(pathToFileURL(html).href);
    await page.getByRole("textbox",{name:"Review notes",exact:true}).fill("Tab one retained note.");
    await otherTab.locator(".queue button").nth(1).click();
    await otherTab.getByRole("textbox",{name:"Review notes",exact:true}).fill("Tab two retained note.");
    await page.reload();
    assert.equal(await page.getByRole("textbox",{name:"Review notes",exact:true}).inputValue(),"Tab one retained note.");
    await page.locator(".queue button").nth(1).click();
    assert.equal(await page.getByRole("textbox",{name:"Review notes",exact:true}).inputValue(),"Tab two retained note.");
    await otherTab.close();
    await page.getByRole("combobox",{name:"Ending filter"}).selectOption("margin");
    assert.equal(await page.locator(".queue button").count(),25);
    await page.getByRole("combobox",{name:"Ending filter"}).selectOption("all");
    assert.equal(await page.locator(".queue button").count(),108);
    await page.getByRole("searchbox",{name:"Search endings"}).fill("083");
    assert.equal(await page.locator(".queue button").count(),1);
    assert.match(await page.locator(".result-row").innerText(), /53.50/);
    await page.getByRole("searchbox",{name:"Search endings"}).fill("no-matching-player");
    assert.match(await page.locator(".detail").innerText(),/No matching endings/);
    await page.getByRole("button",{name:"2. Admission",exact:true}).click();
    assert.equal(await page.locator(".queue button").count(),241);
    await page.getByRole("searchbox",{name:"Search admission"}).fill("chika");
    assert.ok(await page.locator(".queue button").count()>0);
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("button",{name:"Download original SGF",exact:true}).click();
    const sgfDownload = await downloadPromise;
    const sgfPath = path.join(temporary,"source.sgf");await sgfDownload.saveAs(sgfPath);
    assert.match(await fs.readFile(sgfPath,"utf8"),/\(;.*GM\[1\]/s);
    await page.getByRole("combobox",{name:"Admission filter"}).selectOption("excluded");
    await page.getByRole("searchbox",{name:"Search admission"}).fill("");
    assert.equal(await page.locator(".queue button").count(),759);
    await page.getByRole("button",{name:"3. Examples",exact:true}).click();
    assert.ok(await page.locator(".queue button").count()>20);
    const example = await page.evaluate(()=>JSON.parse(document.getElementById("review-data").textContent).examples[0]);
    const moverRank = await page.getByRole("row").filter({has:page.getByRole("cell",{name:"Mover rank",exact:true})}).getByRole("cell").nth(1).innerText();
    assert.equal(moverRank,example.rank_valid[0]?example.metadata.source_rank_mover:"unknown");
    const opponentRank = await page.getByRole("row").filter({has:page.getByRole("cell",{name:"Opponent rank",exact:true})}).getByRole("cell").nth(1).innerText();
    assert.equal(opponentRank,example.rank_valid[1]?example.metadata.source_rank_opponent:"unknown");
    await page.getByRole("combobox",{name:"Stored board plane"}).selectOption("own");
    await page.getByRole("checkbox",{name:"Show legal moves"}).uncheck();
    assert.match(await page.locator(".detail").innerText(),/Masked; zero is not a measured duration/);
    await page.getByRole("button",{name:"4. Sign-off checklist",exact:true}).click();
    assert.equal(await page.getByRole("textbox",{name:"Review notes",exact:true}).count(),6);
    const exportPromise = page.waitForEvent("download");
    await page.getByRole("button",{name:"Export notes",exact:true}).click();
    const exported = await exportPromise, notesPath=path.join(temporary,"notes.json");
    await exported.saveAs(notesPath);
    const notes = JSON.parse(await fs.readFile(notesPath,"utf8"));
    assert.equal(notes.notes["ending:44"].status,"followup");
    assert.equal(notes.notes["ending:44"].text,"Tab one retained note.");
    assert.equal(notes.notes["ending:83"].text,"Tab two retained note.");
    await page.evaluate(()=>localStorage.clear());await page.reload();
    await page.locator("#import").setInputFiles(notesPath);
    await page.waitForFunction(()=>document.getElementById("save-status").textContent.includes("Imported notes"));
    assert.match(await page.locator("#save-status").innerText(),/Imported notes/);
    notes.bundle_id="wrong";const wrong=path.join(temporary,"wrong.json");
    await fs.writeFile(wrong,JSON.stringify(notes));await page.locator("#import").setInputFiles(wrong);
    await page.waitForFunction(()=>document.getElementById("save-status").textContent.includes("Import failed"));
    assert.match(await page.locator("#save-status").innerText(),/different evidence bundle/);
    await page.reload();
    await page.screenshot({path:path.join(path.dirname(html),"desktop.png"),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
    await page.screenshot({path:path.join(path.dirname(html),"mobile.png"),fullPage:true});
    const noStorage = await context.newPage();
    await noStorage.addInitScript(()=>Object.defineProperty(window,"localStorage",{get(){throw Error("disabled");}}));
    await noStorage.goto(pathToFileURL(html).href);
    assert.match(await noStorage.locator("#save-status").innerText(),/storage unavailable/);
    assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
    console.log("PASS: offline load, replay, filters, SGF download, stored examples, notes persistence across tabs/export/import, wrong-bundle rejection, storage fallback, desktop/mobile layout; no network or page errors.");
  } finally {await browser.close();await fs.rm(temporary,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
